import { test, expect } from '@playwright/test';
test('upload, create, edit, approve, schedule, persist and export', async ({ page }) => {
 const errors = [];
 page.on('pageerror', error => errors.push(error.message));
 await page.goto('/');
 await expect(page.getByRole('heading', { name: 'A little less busywork.' })).toBeVisible();
 await page.screenshot({ path: '/tmp/creatoros-overview.png', fullPage: true });
 await page.locator('input[type=file]').setInputFiles({ name: 'test-media.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="50" height="50"><rect width="50" height="50" fill="green"/></svg>') });
 await expect(page.getByRole('status')).toContainText('1 file saved');
 await page.getByRole('button', { name: 'Content inbox', exact: true }).click();
 await expect(page.getByText('test-media.svg', {exact:true})).toBeVisible();
 await page.getByRole('button', { name: 'Preview', exact:true }).click();
 await expect(page.getByRole('img', { name: 'test-media.svg' })).toBeVisible();
 await page.getByRole('button', {name:'Close dialog'}).click();
 await page.getByRole('button', { name: 'Create draft', exact:true }).click();
 await page.getByLabel('Draft title').fill('The perfect rally');
 await page.getByLabel('Caption', {exact:true}).fill('One team. One unforgettable point.');
 await page.getByLabel('TikTok', {exact:true}).check();
 await page.getByLabel('Includes rights').check();
 await page.getByRole('button', {name:'Save for review'}).click();
 await page.getByRole('button', {name:'Open The perfect rally'}).click();
 await expect(page.getByRole('button', {name:'Add to local calendar'})).toHaveCount(0);
 await page.getByRole('button', {name:'Approve draft', exact:true}).click();
 await page.getByRole('button', {name:'Open The perfect rally'}).click();
 await page.getByRole('button', {name:'Edit draft'}).click();
 await page.getByLabel('Caption', {exact:true}).fill('Updated caption, ready for human review.');
 await page.getByRole('button', {name:'Save for review'}).click();
 await page.getByRole('button', {name:'Open The perfect rally'}).click();
 await expect(page.getByRole('button', {name:'Approve draft', exact:true})).toBeVisible();
 await page.getByRole('button', {name:'Approve draft', exact:true}).click();
 await page.getByRole('button', {name:'Open The perfect rally'}).click();
 await page.getByLabel('Schedule date and time', {exact:true}).fill('2099-05-12T14:30');
 await page.getByRole('button', {name:'Add to local calendar'}).click();
 await page.getByRole('button', {name:'Calendar',exact:true}).click();
 await expect(page.getByRole('heading', {name:'The perfect rally'})).toBeVisible();
 await page.reload();
 await page.getByRole('button', {name:'Calendar',exact:true}).click();
 await expect(page.getByRole('heading', {name:'The perfect rally'})).toBeVisible();
 await page.getByRole('button', {name:'Settings & connections'}).click();
 const promise = page.waitForEvent('download');
 await page.getByRole('button', {name:'Export workspace JSON'}).click();
 const download = await promise;
 const stream = await download.createReadStream(); let content='';for await (const chunk of stream) content+=chunk.toString();
 const state=JSON.parse(content);
 expect(state.drafts[0].status).toBe('scheduled');
 expect(state.drafts[0].caption).toBe('Updated caption, ready for human review.');
 expect(state.audit.some(a=>a.action==='edited draft; approval reset')).toBe(true);
 expect(state.assets).toHaveLength(1);
 expect(errors).toEqual([]);
});
test('mobile layout stays within viewport and can create a draft', async ({ page }) => {
 await page.setViewportSize({ width: 390, height: 844 });
 await page.goto('/');
 await expect(page.getByRole('heading', { name: 'A little less busywork.' })).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.getByRole('button', {name:'Create content',exact:true}).click();
 await page.getByLabel('Draft title').fill('Mobile post');
 await page.getByRole('button',{name:'Save for review'}).click();
 await expect(page.getByRole('heading',{name:'Mobile post'})).toBeVisible();
 await page.screenshot({path:'/tmp/creatoros-mobile.png',fullPage:true});
});
